/** Writes typed ABIs for the web app (web/src/generated/abis.ts). Run after `hardhat compile`. */
import fs from "fs";
import path from "path";

const CONTRACTS: Record<string, string> = {
  machineAbi: "Machine.sol/Machine",
  factoryAbi: "MachineFactory.sol/MachineFactory",
  bidBookAbi: "BidBook.sol/BidBook",
  floorBookAbi: "FloorBook.sol/FloorBook",
  oddsAbi: "OddsMarket.sol/OddsMarket",
  registryAbi: "CollectionRegistry.sol/CollectionRegistry",
  mockUsdcAbi: "mocks/Mocks.sol/MockUSDC",
  mockCollectionAbi: "mocks/Mocks.sol/MockCollection",
  mockRandomnessAbi: "randomness/MockRandomnessProvider.sol/MockRandomnessProvider",
};

const root = path.join(__dirname, "..");
let out = "// Generated by contracts/scripts/export-abis.ts. Do not edit.\n\n";
for (const [name, rel] of Object.entries(CONTRACTS)) {
  const file = path.join(root, "artifacts", "contracts", `${rel}.json`);
  const abi = JSON.parse(fs.readFileSync(file, "utf8")).abi;
  out += `export const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
const target = path.join(root, "..", "web", "src", "generated", "abis.ts");
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out);
console.log(`Wrote ${target}`);
