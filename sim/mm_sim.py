#!/usr/bin/env python3
"""Returns of an NFT floor market-making order: informed arbitrage only vs adding uninformed gacha flow.

The order mirrors Tensor's two-sided market-making orders:
  - ask S; bid B = S / (1 + delta) x (1 - spread fee)
  - someone buys an NFT from the order: S <- S x (1 + delta); someone sells one in: S <- S / (1 + delta)
The outside floor M random-walks hourly. Two kinds of flow:
  - Informed arbitrage: buys when the order's ask is below the outside floor (net of friction), sells in when its bid is above
  - Uninformed flow: draw machines buy floor NFTs from the order (random arrivals) and players sell won floor NFTs back
    (at half the buy rate). Gacha flow ignores outside prices.

Metric: value of the order after 90 days minus the value of simply holding the initial assets, as a share of the initial assets.
Everything is marked at the ending outside floor.

Usage:
  python3 sim/mm_sim.py > sim/mm_results.md
"""

import numpy as np

HOURS = 90 * 24
VOL_DAILY = 0.04  # daily volatility of the collection floor
DELTA = 0.03
FEE = 0.04  # market-making spread fee
ARB_COST = 0.02  # arbitrageur cost on outside markets (fees, royalties, slippage)
CASH0 = 10.0  # initial cash in floor units
NFTS0 = 10
RUNS = 300


def run(rng, draws_per_day, fee=FEE, delta=DELTA):
    m = 1.0
    s = 1.0 * (1 + delta)  # initial ask slightly above the floor
    cash, nfts = CASH0, NFTS0
    vol = VOL_DAILY / np.sqrt(24)
    lam_buy = draws_per_day / 24
    lam_sell = lam_buy / 2
    fees = 0.0
    for _ in range(HOURS):
        m *= np.exp(rng.normal(0, vol))
        # uninformed flow
        for _ in range(rng.poisson(lam_buy)):
            if nfts > 0:
                cash += s
                nfts -= 1
                s *= 1 + delta
        for _ in range(rng.poisson(lam_sell)):
            b = s / (1 + delta) * (1 - fee)
            if cash >= b:
                cash -= b
                nfts += 1
                fees += s / (1 + delta) * fee
                s /= 1 + delta
        # informed arbitrage
        while nfts > 0 and s < m * (1 - ARB_COST):
            cash += s
            nfts -= 1
            s *= 1 + delta
        while True:
            b = s / (1 + delta) * (1 - fee)
            if cash >= b and b > m * (1 + ARB_COST):
                cash -= b
                nfts += 1
                s /= 1 + delta
            else:
                break
    value = cash + nfts * m
    hold = CASH0 + NFTS0 * m
    initial = CASH0 + NFTS0 * 1.0
    return (value - hold) / initial


def main():
    rng = np.random.default_rng(3)
    out = ["# Floor market-making returns: the effect of gacha flow", "",
           "Generated by `python3 sim/mm_sim.py`. Assumptions are in the script's docstring.",
           f"Initial assets: {CASH0:.0f} floors of cash + {NFTS0} floor NFTs; delta = {DELTA:.0%}, spread fee = {FEE:.0%}, "
           f"floor volatility {VOL_DAILY:.0%}/day, arbitrage cost {ARB_COST:.0%}, 90 days, {RUNS} paths.", "",
           "| Floor NFTs bought from the order by spins per day | Excess return vs holding (median) | P10 | P90 | Paths underperforming holding |",
           "|---|---|---|---|---|"]
    for draws in (0, 1, 3, 6, 12):
        res = np.array([run(rng, draws) for _ in range(RUNS)])
        out.append(f"| {draws} | {np.median(res) * 100:+.1f}% | {np.percentile(res, 10) * 100:+.1f}% "
                   f"| {np.percentile(res, 90) * 100:+.1f}% | {np.mean(res < 0) * 100:.0f}% |")
    print("\n".join(out))


if __name__ == "__main__":
    main()
